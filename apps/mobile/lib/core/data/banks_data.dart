import 'dart:convert';
import 'package:http/http.dart' as http;

class BankInfo {
  final String id;
  final String name;
  final String app;
  final String code;
  final String pkg;
  final String category; // 'commercial', 'neobank', 'ewallet', 'business'
  final String logo;
  final String guide;

  const BankInfo({
    required this.id,
    required this.name,
    required this.app,
    required this.code,
    required this.pkg,
    required this.category,
    required this.logo,
    required this.guide,
  });

  String get assetKey {
    if (id.startsWith('vcb')) return 'vcb';
    if (id.startsWith('bidv') || id.startsWith('bidc')) return 'bidv';
    if (id.startsWith('tcb')) return 'tcb';
    if (id.contains('mb') && id != 'mbv' && id != 'cimb') return 'mb';
    if (id.startsWith('acb')) return 'acb';
    if (id.startsWith('vib')) return 'vib';
    if (id.startsWith('lpb')) return 'lpb';
    if (id == 'ab_ditizen_biz') return 'abb';
    if (id == 'lio') return 'ocb';
    return id.toLowerCase();
  }
}

class BankDataRepository {
  static List<BankInfo> _liveBanks = [];
  static List<BankInfo> get banks => _liveBanks.isNotEmpty ? _liveBanks : defaultBanks;

  static Future<void> fetchFromBackend(String apiBaseUrl) async {
    try {
      final uri = Uri.parse('$apiBaseUrl/admin/banks');
      final res = await http.get(uri).timeout(const Duration(seconds: 4));
      if (res.statusCode == 200) {
        final List<dynamic> list = jsonDecode(res.body);
        final loaded = <BankInfo>[];
        for (final item in list) {
          if (item['isActive'] == false) continue;
          loaded.add(BankInfo(
            id: (item['code'] ?? item['id'] ?? '').toString().toLowerCase(),
            name: item['name'] ?? '',
            app: item['app'] ?? item['name'] ?? '',
            code: item['code'] ?? '',
            pkg: item['pkg'] ?? '',
            category: item['category'] ?? 'commercial',
            logo: item['logo'] ?? '',
            guide: item['guide'] ?? '',
          ));
        }
        if (loaded.isNotEmpty) {
          _liveBanks = loaded;
        }
      }
    } catch (_) {}
  }

